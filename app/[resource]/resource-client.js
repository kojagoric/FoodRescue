 "use client";
import { useState } from "react";
import { useRouter } from "next/navigation";

export default function ResourceClient({resource, rows, fields}) {
  const [json,setJson] = useState("{}");
  const [message,setMessage] = useState("");
  const [error,setError] = useState("");
  const router = useRouter();

  async function create(e) {
    e.preventDefault(); setMessage(""); setError("");
    let payload;
    try { payload = JSON.parse(json); }
    catch { setError("Enter valid JSON."); return; }
    const response = await fetch(`/api/${resource}`, {
      method:"POST", headers:{"Content-Type":"application/json"}, body:JSON.stringify(payload)
    });
    const result = await response.json();
    if (!response.ok) { setError(result.error || "Could not create record."); return; }
    setMessage("Record created successfully."); setJson("{}"); router.refresh();
  }

  return <>
    <section className="card">
      <h2>Add a record</h2>
      <p className="muted">Use the exact column names shown below. Auto-increment IDs are generated by MySQL.</p>
      <p className="muted">{fields.join(", ")}</p>
      <form onSubmit={create}>
        <textarea rows={7} value={json} onChange={e=>setJson(e.target.value)} />
        {error && <p className="error">{error}</p>}
        {message && <p className="success">{message}</p>}
        <button>Create record</button>
      </form>
    </section>
    <section className="tablewrap">
      {rows.length === 0 ? <p>No records yet.</p> : <table>
        <thead><tr>{Object.keys(rows[0]).map(k=><th key={k}>{k}</th>)}</tr></thead>
        <tbody>{rows.map((row,i)=><tr key={i}>{Object.values(row).map((v,j)=><td key={j}>{v === null ? "—" : String(v)}</td>)}</tr>)}</tbody>
      </table>}
    </section>
  </>;
}
